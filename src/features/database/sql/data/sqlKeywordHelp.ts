// 긴 구문부터 매칭해 LEFT JOIN을 LEFT/JOIN으로, NOT NULL을 NOT/NULL로 쪼개지 않습니다.
const ordered = [...sqlKeywordHelp].sort((a, b) => b.keyword.length - a.keyword.length)
const pattern = new RegExp(`\\b(?:${ordered.map(entry => entry.keyword.replaceAll(' ', '\\s+')).join('|')})\\b`, 'gi')
export function findSqlKeywordHelp(text: string): SqlKeywordHelp[] {
  const withoutLiterals = text.replace(/--[^\n]*|\/\*[\s\S]*?\*\/|'(?:''|[^'])*'|"(?:""|[^"])*"|`[^`]*`/g, ' ')
  const selected = new Set<string>()
  for (const match of withoutLiterals.matchAll(pattern)) selected.add(match[0].replace(/\s+/g, ' ').toUpperCase())
  return [...selected].map(keyword => sqlKeywordHelp.find(entry => entry.keyword === keyword)!).filter(Boolean)
}
